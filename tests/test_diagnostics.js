'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const code=fs.readFileSync(__dirname+'/../js/portal.core.js','utf8');
const window={PORTAL_CONFIG:{passwordRequired:true}};
const document={readyState:'loading',addEventListener:()=>{},getElementById:()=>null};
vm.runInNewContext(code,{window,document,setTimeout,clearTimeout,XMLHttpRequest:function(){}},{filename:'portal.core.js'});
const p=window.PortalDiagnostics;
const check=(v,code,text)=>{let r=p.classifyHotspotError(v,true);assert.equal(r.code,code);assert.ok(r.message.includes(text),JSON.stringify(r));};
check('no more sessions are allowed','SESSION_LIMIT','جهاز آخر');
check('transfer limit reached','DATA_LIMIT','رصيد');
check('account has expired','EXPIRED','صلاحية');
check('not enough credit','NO_CREDIT','رصيد');
check('wrong password','INVALID_PASSWORD','كلمة المرور');
check('invalid username','INVALID_USERNAME','الكرت خطأ');
check('radius timeout','AUTH_SERVER_UNAVAILABLE','خادم');
check('no valid profile','NO_VALID_PROFILE','باقة فعالة');
check('access-reject','REJECTED','تعذر تسجيل الدخول');
assert.equal(p.isLoggedIn('yes'),true);assert.equal(p.isLoggedIn('no'),false);
assert.equal(p.normalize('۱۲٣٤ ٥',true),'12345');
console.log('PASS: RouterOS error classification, session limits, quota, login state, input normalization');
